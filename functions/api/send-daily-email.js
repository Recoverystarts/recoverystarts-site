// Daily Reflection Email Sender
// Fetches today's reflection from our RSS feed and sends via Buttondown API
// Triggered by external cron (cron-job.org or Zapier) hitting this endpoint
// Protected by a secret token

export async function onRequestGet(context) {
  const url = new URL(context.request.url);
  const token = url.searchParams.get('token');
  const expectedToken = context.env.DAILY_EMAIL_TOKEN;

  // Security: require token match
  if (!expectedToken || !token || token !== expectedToken) {
    return new Response(JSON.stringify({ error: 'Unauthorized' }), {
      status: 401,
      headers: { 'Content-Type': 'application/json' }
    });
  }

  const BUTTONDOWN_API_KEY = context.env.BUTTONDOWN_API_KEY;
  if (!BUTTONDOWN_API_KEY) {
    return new Response(JSON.stringify({ error: 'Missing BUTTONDOWN_API_KEY' }), {
      status: 500,
      headers: { 'Content-Type': 'application/json' }
    });
  }

  try {
    // Get today's date in Mountain Time
    const now = new Date();
    const formatter = new Intl.DateTimeFormat('en-US', {
      timeZone: 'America/Edmonton',
      month: 'long',
      day: 'numeric',
      year: 'numeric'
    });
    const parts = formatter.formatToParts(now);
    const monthName = parts.find(p => p.type === 'month').value;
    const day = parseInt(parts.find(p => p.type === 'day').value);
    const year = parts.find(p => p.type === 'year').value;
    const slug = `${monthName.toLowerCase()}-${day}`;
    const displayDate = `${monthName} ${day}, ${year}`;

    // Fetch today's reflection page
    const pageUrl = `https://recoverystarts.com/daily-reflections/${slug}`;
    const pageResp = await fetch(pageUrl);
    if (!pageResp.ok) {
      return new Response(JSON.stringify({
        error: `Failed to fetch reflection page: ${pageResp.status}`,
        url: pageUrl
      }), { status: 500, headers: { 'Content-Type': 'application/json' } });
    }
    const html = await pageResp.text();

    // Extract the reflection content from the page
    // The page has a <main> section with the reflection content
    const titleMatch = html.match(/<h1[^>]*class="[^"]*reflection-title[^"]*"[^>]*>(.*?)<\/h1>/s);
    const thoughtMatch = html.match(/<section[^>]*class="[^"]*einstein-thought[^"]*"[^>]*>([\s\S]*?)<\/section>/);
    const bookRefMatch = html.match(/<section[^>]*class="[^"]*book-reference[^"]*"[^>]*>([\s\S]*?)<\/section>/);
    const discussionMatch = html.match(/<section[^>]*class="[^"]*discussion[^"]*"[^>]*>([\s\S]*?)<\/section>/);

    // Build clean text from HTML sections
    function stripHtml(str) {
      if (!str) return '';
      return str
        .replace(/<[^>]*>/g, '')
        .replace(/&amp;/g, '&')
        .replace(/&lt;/g, '<')
        .replace(/&gt;/g, '>')
        .replace(/&quot;/g, '"')
        .replace(/&#039;/g, "'")
        .replace(/&nbsp;/g, ' ')
        .replace(/\s+/g, ' ')
        .trim();
    }

    const title = stripHtml(titleMatch?.[1]) || `Daily Reflection — ${displayDate}`;
    const thought = stripHtml(thoughtMatch?.[1]) || '';
    const bookRef = stripHtml(bookRefMatch?.[1]) || '';
    const discussion = stripHtml(discussionMatch?.[1]) || '';

    // Compose email body in Markdown (Buttondown renders it)
    const emailBody = `# ${title}

*${displayDate}*

---

${thought ? `## Einstein's Perspective\n\n${thought}\n\n` : ''}${bookRef ? `## From the Big Book\n\n${bookRef}\n\n` : ''}${discussion ? `## Something to Think About\n\n${discussion}\n\n` : ''}---

*This reflection was generated by [Recovery Einstein](https://app.recoverystarts.com) — an AI companion grounded in the Big Book of Alcoholics Anonymous.*

[Read today's full reflection on the web](${pageUrl})

[Talk to Einstein about today's reflection](https://app.recoverystarts.com)
`;

    const subject = `☕ ${title}`;

    // Send via Buttondown API
    const bdResp = await fetch('https://api.buttondown.com/v1/emails', {
      method: 'POST',
      headers: {
        'Authorization': `Token ${BUTTONDOWN_API_KEY}`,
        'Content-Type': 'application/json'
      },
      body: JSON.stringify({
        subject: subject,
        body: emailBody,
        status: 'about_to_send',
        email_type: 'public'
      })
    });

    const bdData = await bdResp.json();

    if (!bdResp.ok) {
      return new Response(JSON.stringify({
        error: 'Buttondown API error',
        status: bdResp.status,
        details: bdData
      }), { status: 500, headers: { 'Content-Type': 'application/json' } });
    }

    return new Response(JSON.stringify({
      success: true,
      date: displayDate,
      slug: slug,
      subject: subject,
      emailId: bdData.id,
      status: bdData.status
    }), {
      status: 200,
      headers: { 'Content-Type': 'application/json' }
    });

  } catch (err) {
    return new Response(JSON.stringify({
      error: 'Internal error',
      message: err.message
    }), { status: 500, headers: { 'Content-Type': 'application/json' } });
  }
}
